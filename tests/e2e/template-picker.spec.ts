import { expect, test } from "@playwright/test";
import { mkdir } from "node:fs/promises";
import { resolve } from "node:path";

const evidence = ".local/evidence/templates";
test.beforeAll(async () => { await mkdir(evidence, { recursive: true }); });

test("previews the full score on demand, switches tracks and keeps the chosen starting point through reload", async ({ page }) => {
  test.setTimeout(120_000);
  const loads: string[] = [];
  page.on("request", request => { const path = new URL(request.url()).pathname; if (path.startsWith("/templates/")) loads.push(path); });
  await page.setViewportSize({ width: 1440, height: 900 });
  await page.goto("/");
  await page.locator(".session-rail").getByRole("button", { name: "New session" }).click();
  const draft = page.getByRole("textbox", { name: "Describe your arrangement" });
  await draft.fill("Give the lead a quieter ending.");
  await page.getByRole("button", { name: "Choose a template" }).click();
  const dialog = page.getByRole("dialog", { name: "Arrangement templates" });
  await expect(dialog.getByRole("listitem")).toHaveCount(6);
  expect(loads).toEqual([]);
  await expect(dialog).toHaveCSS("opacity", "1");
  await page.screenshot({ path: evidence + "/desktop-library.png" });
  const player = dialog.locator("audio");
  expect(loads).toEqual([]);
  await dialog.getByRole("button", { name: "Play Patio Radio" }).click();
  await expect(dialog.getByRole("button", { name: "Pause Patio Radio" })).toBeVisible();
  await expect.poll(() => player.evaluate((p: HTMLAudioElement) => p.currentTime)).toBeGreaterThan(0);
  await dialog.getByRole("button", { name: "Pause Patio Radio" }).click();
  expect(await player.evaluate((p: HTMLAudioElement) => p.paused)).toBe(true);
  const seek = dialog.getByRole("slider", { name: "Seek in Patio Radio" });
  await seek.focus();
  await seek.press("End");
  await seek.press("ArrowLeft");
  await expect.poll(() => player.evaluate((p: HTMLAudioElement) => p.currentTime)).toBeGreaterThan(33);
  await dialog.getByRole("button", { name: "Play Tide Almanac" }).click();
  await expect(dialog.getByRole("button", { name: "Pause Tide Almanac" })).toBeVisible();
  await expect(player).toHaveCount(1);
  await page.screenshot({ path: evidence + "/desktop-playing.png" });
  expect(new Set(loads)).toEqual(new Set(["/templates/bossa-nova-v1.mp3", "/templates/tidal-ambient-v1.mp3"]));
  await dialog.getByRole("button", { name: "Use Tide Almanac", exact: true }).click();
  await expect(page.locator(".template-library audio")).toHaveCount(0);
  await expect(draft).toHaveValue("Give the lead a quieter ending.");
  await page.reload();
  await expect(page.getByRole("button", { name: "Tide Almanac" })).toBeVisible();
  await expect(draft).toHaveValue("Give the lead a quieter ending.");
  await page.screenshot({ path: evidence + "/selected-template.png" });
  await draft.fill("");
  await page.getByRole("button", { name: "Create arrangement" }).click();
  await expect(page.locator(".producer-workspace-header")).toContainText("Version 1", { timeout: 90_000 });
  const project = new URL(page.url()).pathname.split("/")[2]!;
  const state = await (await page.request.get("/api/v1/projects/" + project + "/native")).json() as { current: { document: { parts: { role: string }[]; motifs: { partId: string }[] } } };
  expect(state.current.document).toMatchObject({ title: "Tide Almanac", bars: 16, tempoBpm: 66 });
  expect(state.current.document.parts.some((p: { role: string }) => p.role === "percussion")).toBe(false);
  expect(state.current.document.motifs.some((m: { partId: string }) => m.partId === "lead")).toBe(true);
  await expect(page.getByRole("button", { name: "Choose a template" })).toHaveCount(0);
});

test("the phone library recovers from an unavailable preview and leaves the prompt intact on clear", async ({ page }) => {
  await page.goto("/");
  await page.locator(".session-rail").getByRole("button", { name: "New session" }).click();
  await page.setViewportSize({ width: 390, height: 844 });
  const draft = page.getByRole("textbox", { name: "Describe your arrangement" });
  await draft.fill("Add a small answering phrase.");
  await page.getByRole("button", { name: "Choose a template" }).click();
  const dialog = page.getByRole("dialog", { name: "Arrangement templates" });
  await expect(dialog).toHaveCSS("opacity", "1");
  await page.screenshot({ path: evidence + "/phone-library.png" });
  expect(await dialog.evaluate(el => el.scrollWidth <= el.clientWidth && el.getBoundingClientRect().bottom <= innerHeight)).toBe(true);
  const url = "**/templates/synthwave-v1.mp3";
  await page.route(url, route => route.fulfill({ status: 503, body: "" }));
  const play = dialog.getByRole("button", { name: "Play Violet Overpass" });
  await play.click();
  await expect(dialog.getByRole("status")).toContainText("Preview unavailable");
  await expect(dialog.getByRole("button", { name: "Use Violet Overpass", exact: true })).toBeEnabled();
  await page.unroute(url);
  await play.click();
  await expect(dialog.getByRole("button", { name: "Pause Violet Overpass" })).toBeVisible();
  await dialog.getByRole("button", { name: "Use Violet Overpass", exact: true }).click();
  await expect(dialog).toBeHidden();
  await page.getByRole("button", { name: "Remove template" }).click();
  await expect(page.getByRole("button", { name: "Choose a template" })).toBeFocused();
  await expect(draft).toHaveValue("Add a small answering phrase.");
});

test("submits the chosen arrangement, a custom direction and an owned sound together", async ({ page }) => {
  await page.goto("/");
  await page.locator(".session-rail").getByRole("button", { name: "New session" }).click();
  await page.getByRole("button", { name: "Choose a template" }).click();
  await page.getByRole("button", { name: "Use Patio Radio", exact: true }).click();
  await page.getByRole("textbox", { name: "Describe your arrangement" }).fill("Vary the lead phrase and weave in my percussion.");
  await page.getByRole("button", { name: "Add sound", exact: true }).click();
  await page.getByLabel("Upload a WAV source").setInputFiles(resolve(".local/fixtures/owned-percussion.wav"));
  await page.getByRole("checkbox", { name: "Use owned-percussion.wav in the next arrangement change" }).check();
  await page.keyboard.press("Escape");
  const checked = page.waitForRequest(r => r.method() === "POST" && r.url().endsWith("/native/interpretations"));
  const constructed = page.waitForRequest(r => r.method() === "POST" && r.url().endsWith("/native/constructions"));
  await page.getByRole("button", { name: "Create arrangement", exact: true }).click();
  expect((await checked).postDataJSON()).toMatchObject({ templateId: "bossa-nova-v1" });
  expect((await constructed).postDataJSON()).toMatchObject({ templateId: "bossa-nova-v1", sourceAssetIds: [expect.any(String)] });
  await expect(page.locator(".producer-workspace-header")).toContainText("Version 1", { timeout: 90_000 });
  const id = new URL(page.url()).pathname.split("/")[2]!;
  const state = await (await page.request.get("/api/v1/projects/" + id + "/native")).json() as { current: { document: { sourceAssetIds: string[]; motifs: { id: string }[] } } };
  expect(state.current.document).toMatchObject({ title: "Patio Radio", tempoBpm: 112 });
  expect(state.current.document.sourceAssetIds).toHaveLength(1);
  expect(state.current.document.motifs.some(m => m.id.startsWith("variation-"))).toBe(true);
});
